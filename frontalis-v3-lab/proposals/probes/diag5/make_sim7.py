"""Generate sim7.py from sim6.py (LADDER section 9, the "either could have done it" fog). The ONLY change: in the ambiguous
contexts (even context ids, AMB_CTX), the outcome is mixed toward the mean of the two entities present:
    db = (1 - amb) * M[actor, c] + amb * 0.5 * (M[e1, c] + M[e2, c])      (config key `amb`, default 0.0 = sim6)
so the outcome itself stays clear (noise 0.1 as in F1) but the two entities become hard to tell apart in those contexts.
The script refuses to write if a pattern is not found exactly once."""
from pathlib import Path

HERE = Path(__file__).resolve().parent
src = (HERE / "sim6.py").read_text(encoding="utf-8")
LINE = 'db = torch.where(AVG[wid][:, None], 0.5 * (MM[wid, e1, cc] + MM[wid, e2, cc]), db)'
REPL = [(LINE, LINE + '\n            amb_w = c["amb"] * (cc % 2 == 0).float()      # sim7: ambiguous (even) contexts'
                      '\n            db = (1 - amb_w)[:, None] * db + amb_w[:, None] * 0.5 * (MM[wid, e1, cc] + MM[wid, e2, cc])'),
        ("noise=0.1,", "noise=0.1, amb=0.0,")]
for a, b in REPL:
    assert src.count(a) == 1, a
    src = src.replace(a, b)
src = "# GENERATED by make_sim7.py from sim6.py: ambiguous contexts mix the outcome toward the pair mean (config `amb`). Do not edit.\n" + src
(HERE / "sim7.py").write_text(src, encoding="utf-8")
print("wrote sim7.py")
