"""Generate sim6.py from sim5.py (LADDER section 8, the fog world). The ONLY change: the outcome noise scale becomes a config
key `noise` (default 0.1 = sim5). Everything else is byte-identical; the script refuses to write if a pattern is not found once."""
from pathlib import Path

HERE = Path(__file__).resolve().parent
src = (HERE / "sim5.py").read_text(encoding="utf-8")
REPL = [('db = db + 0.1 * G["NZ"][:, tl]', 'db = db + c["noise"] * G["NZ"][:, tl]'),
        ("kmax=10.0,", "kmax=10.0, noise=0.1,")]
for a, b in REPL:
    assert src.count(a) == 1, a
    src = src.replace(a, b)
src = "# GENERATED by make_sim6.py from sim5.py: outcome noise scale is the config key `noise` (default 0.1). Do not edit.\n" + src
(HERE / "sim6.py").write_text(src, encoding="utf-8")
print("wrote sim6.py")
